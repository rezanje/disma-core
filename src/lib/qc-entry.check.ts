import assert from 'node:assert/strict';
import { prepareQcEntry } from './qc-entry';
const item:any={id:'leaf',purchaseId:'doc',productId:'p',qtyTarget:10,qtyPurchased:0,estimatedUnitPrice:10,purchaseMethod:'Pasar'};
const context:any={eventId:'entry-1',needsArrival:true,evidence:{performedBy:'worker',occurredAt:'2026-10-17T04:00:00+07:00',paperNumber:'QC-1'},orders:[{id:'po',status:'Belanja',orderDate:'2026-10-16'}],lines:[{salesOrderId:'po',productId:'p',qty:5}]};
const draft:any={incoming:6,passed:5,rejected:1,rejectAction:'Disposal',rejectReason:'Busuk'};
const plan=prepareQcEntry(item,draft,context);
assert.equal(plan.arrival?.payload.qty,6,'enter physical arrival and QC from the same row');
assert.equal(plan.qc.allocations[0].qty,5);
assert.equal(plan.qc.qtyPassToInventory,0);
assert.equal(plan.qc.qtyReject,1);
assert.equal(plan.qc.vendorUnitPrice,undefined,'no financial price required for unreported market goods');
assert.equal(plan.arrival?.payload.paperNumber,plan.qc.paperNumber);
assert.throws(()=>prepareQcEntry(item,{...draft,passed:6},context),/Masuk harus sama/);
assert.throws(()=>prepareQcEntry(item,{...draft,incoming:11,passed:10},context),/melebihi/);
assert.throws(()=>prepareQcEntry(item,{...draft,rejectReason:''},context),/alasan reject/i);
assert.throws(()=>prepareQcEntry(item,draft,{...context,evidence:{}}),/pemeriksa/i);
assert.throws(()=>prepareQcEntry(item,{...draft,incoming:NaN},context),/angka/i);
const ready={...item,physicalBeforeReport:true,physicalQtyReceived:6,qcProcessedQty:2};
const retry=prepareQcEntry(ready,{...draft,incoming:4,passed:3}, {...context,needsArrival:false});
assert.equal(retry.arrival,undefined,'received stock must never be entered a second time');
assert.equal(retry.qc.qtyReject,1);
const extra=prepareQcEntry(item,{...draft,incoming:10,passed:9},context);
assert.equal(extra.qc.qtyPassToInventory,4,'passed quantity in excess of PO demand goes to free inventory');
const manual=prepareQcEntry(item,{...draft,allocations:[{soId:'po',qty:2}]},context);
assert.equal(manual.qc.qtyPassToInventory,3,'manual PO allocation retains the remainder as warehouse stock');
assert.throws(()=>prepareQcEntry(item,{...draft,allocations:[{soId:'po',qty:7}]},context),/alokasi/i);
console.log('direct QC row planning: OK');
const vendor={...item,purchaseMethod:'Vendor',qtyPurchased:10,actualUnitPrice:10,paymentMethod:'Transfer'};
assert.throws(()=>prepareQcEntry(vendor,draft,{...context,actorRole:'finance'}),/rekening/i,'select a payment source before recording physical arrival');
assert.throws(()=>prepareQcEntry({...vendor,paymentMethod:'Cash'},{...draft,vendorUnitPrice:Infinity},context),/harga/i);
