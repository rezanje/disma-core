import assert from 'node:assert/strict';
import * as quantities from './shopping-quantities';
assert.equal(typeof quantities.shoppingQuantities,'function','shopping rows must resolve editable quantities independently of the legacy warehouse-only flag');
const {shoppingQuantities,shoppingDocumentItems}=quantities;
const row={id:'leek_po',productId:'leek',salesOrderId:'po',quantity:10,fromStock:true,estimatedPrice:12,sellPrice:18};
const partial=shoppingQuantities([row],{leek:7});
assert.equal(partial[0].totalQty,3,'10 needed minus 7 free stock defaults to buying 3 even for a warehouse-marked row');
assert.equal(partial[0].allocatedStock,7);
assert.equal(shoppingQuantities([row],{leek:12})[0].totalQty,0);
assert.equal(shoppingQuantities([row],{leek:0})[0].totalQty,10);
assert.equal(shoppingQuantities([row],{leek:7},{leek:4})[0].totalQty,7,'stock reserved by other POs is unavailable');
const extra=shoppingQuantities([row],{leek:7},{},{},{leek_po:5});
assert.equal(extra[0].totalQty,5,'an explicit purchase quantity must remain editable');
assert.equal(extra[0].poPurchaseQty,3);
assert.equal(extra[0].stockPurchaseQty,2);
const lines=shoppingDocumentItems(extra);
assert.deepEqual(lines.map(line=>[line.salesOrderId,line.totalQty]),[['po',3],[undefined,2]],'extra purchase is a separate warehouse line, never excess PO allocation');
assert.equal(lines[1].sellPrice,0);
assert.equal(shoppingDocumentItems(shoppingQuantities([row],{leek:12},{},{},{leek_po:2}))[0].salesOrderId,undefined,'top up stock even when the PO is fully covered');
const shared=shoppingQuantities([row,{...row,id:'leek_po2',salesOrderId:'po2'}],{leek:7});
assert.deepEqual(shared.map(line=>line.totalQty),[3,10],'warehouse stock cannot be allocated twice');
assert.equal(shoppingQuantities([row],{leek:7},{},{leek_po:2})[0].totalQty,1,'existing PO sourcing is deducted once');
const manual=shoppingQuantities([{...row,id:'manual',salesOrderId:undefined,quantity:5}],{leek:100});
assert.equal(manual[0].totalQty,5,'a deliberate warehouse top-up is not fulfilled from existing stock');
assert.equal(manual[0].allocatedStock,0);
assert.equal(shoppingDocumentItems(manual)[0].salesOrderId,undefined);
assert.equal(shoppingQuantities([{...row,quantity:.3}],{leek:.1})[0].totalQty,.2);
assert.equal(shoppingDocumentItems(shoppingQuantities([row],{leek:20})).length,0,'stock-only fulfillment creates no purchase lines');
console.log('shopping shortfall, editable purchase quantities and stock top-up checks passed');
