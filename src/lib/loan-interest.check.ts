import assert from 'node:assert/strict';
import { calculateLoanInterest, describeLoanInterest, loanPaymentDebits, type LoanInterestTerms } from './loan-interest';
const terms: LoanInterestTerms = { mode: 'percent', period: 'monthly', value: 2, months: 3 };
assert.deepEqual(calculateLoanInterest(70000000, terms), { periodInterest: 1400000, totalInterest: 4200000, totalRepayment: 74200000 });
assert.equal(calculateLoanInterest(70000000, { ...terms, period: 'total' }).totalInterest, 1400000);
assert.equal(calculateLoanInterest(70000000, { ...terms, value: 1.5 }).totalInterest, 3150000);
assert.equal(calculateLoanInterest(70000000, { ...terms, mode: 'amount', value: 1000000 }).totalInterest, 3000000);
assert.equal(calculateLoanInterest(70000000, { ...terms, mode: 'amount', period: 'total', value: 1000000 }).totalInterest, 1000000);
assert.equal(calculateLoanInterest(70000000, { ...terms, value: 0 }).totalInterest, 0);
for (const value of [-1, NaN, Infinity]) assert.throws(() => calculateLoanInterest(70000000, { ...terms, value }));
for (const months of [0, -1, 1.5, Infinity]) assert.throws(() => calculateLoanInterest(70000000, { ...terms, months }));
assert.throws(() => calculateLoanInterest(0, terms));
assert.throws(() => calculateLoanInterest(Number.MAX_SAFE_INTEGER, terms));
assert.match(describeLoanInterest(70000000, terms), /2% dari pokok awal per bulan × 3 bulan; total bunga Rp4\.200\.000,00/);
assert.deepEqual(loanPaymentDebits(2400000, 1000000), [{ accountCode: '2-4000', amount: 1000000 }, { accountCode: '6-3000', amount: 1400000 }]);
assert.deepEqual(loanPaymentDebits(1400000, 0), [{ accountCode: '6-3000', amount: 1400000 }]);
assert.deepEqual(loanPaymentDebits(1000000, 1000000), [{ accountCode: '2-4000', amount: 1000000 }]);
for (const principal of [-1, 2500000, NaN]) assert.throws(() => loanPaymentDebits(2400000, principal));
console.log('loan-interest: OK');
